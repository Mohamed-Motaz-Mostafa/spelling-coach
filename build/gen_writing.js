// Builds the stored bank of IELTS Writing tasks with band-9 model answers (Gemini, free tier), using the same
// prompts and checks as the app (app/ai.js). Every answer is saved to build/curated/writing_bank.json as soon as it
// arrives, so a re-run only fills the gaps; the bank is then published to data/writing.js for the app.
//
// Usage: node build/gen_writing.js [--per-type N] [--publish-only]
//   --per-type N    tasks per chart type and per essay type (default 2: 10 Task 1 + 10 Task 2)
//   --publish-only  rewrite data/writing.js from the stored bank without calling the API
// Keys come from SC_AI_KEYS (comma-separated) or app/ai-keys.local.js.
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const AI = require('../app/ai.js');

const ROOT = path.join(__dirname, '..');
const BANK = path.join(__dirname, 'curated', 'writing_bank.json');
const OUT = path.join(ROOT, 'data', 'writing.js');
const US2UK = path.join(__dirname, 'raw', 'american_spellings.json');

function arg(name, def) {
  const i = process.argv.indexOf(name);
  return i < 0 ? def : process.argv[i + 1];
}

function loadKeys() {
  if (process.env.SC_AI_KEYS) return process.env.SC_AI_KEYS.split(',').map((k) => k.trim()).filter(Boolean);
  const file = path.join(ROOT, 'app', 'ai-keys.local.js');
  if (!fs.existsSync(file)) return [];
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(file, 'utf8'), sandbox);
  return (sandbox.window.SC_AI_KEYS || []).filter(Boolean);
}

// US -> UK spellings for the British safety net, minus the forms that are also correct British words.
function loadMap() {
  const raw = JSON.parse(fs.readFileSync(US2UK, 'utf8'));
  const out = {};
  Object.keys(raw).sort().forEach((k) => {
    const us = k.toLowerCase(), uk = String(raw[k]).toLowerCase();
    if (/^[a-z]+$/.test(us) && /^[a-z]+$/.test(uk) && us !== uk && !AI.STOP.test(us)) out[us] = uk;
  });
  return out;
}

// Spread the topics so that tasks of the same kind do not share one.
function plan(perType) {
  const specs = [];
  let n = 0;
  Object.keys(AI.CHARTS).forEach((type, ti) => {
    for (let k = 0; k < perType; k++) specs.push({ id: `t1-${type}-${k + 1}`, task: 1, type, topic: AI.TOPICS[(ti * 3 + k * 7) % AI.TOPICS.length], order: n++ });
  });
  Object.keys(AI.ESSAYS).forEach((type, ti) => {
    for (let k = 0; k < perType; k++) specs.push({ id: `t2-${type}-${k + 1}`, task: 2, type, topic: AI.TOPICS[(ti * 3 + k * 7 + 11) % AI.TOPICS.length], order: n++ });
  });
  return specs;
}

function publish(bank, map) {
  const order = plan(+arg('--per-type', 2)).reduce((o, s) => { o[s.id] = s.order; return o; }, {});
  const rank = (t) => (order[t.id] == null ? 999 : order[t.id]);
  const tasks = bank.slice().sort((a, b) => rank(a) - rank(b) || (a.id < b.id ? -1 : 1));
  const data = { built: new Date().toISOString().slice(0, 10), tasks, us2uk: map };
  fs.writeFileSync(OUT, '/* Generated by build/gen_writing.js from build/curated/writing_bank.json - do not edit by hand. */\n' +
    'window.SC_WRITING=' + JSON.stringify(data) + ';\n');
  console.log(`published ${tasks.length} tasks and ${Object.keys(map).length} US->UK spellings to data/writing.js`);
}

async function main() {
  const map = loadMap();
  const bank = fs.existsSync(BANK) ? JSON.parse(fs.readFileSync(BANK, 'utf8')) : [];
  if (process.argv.includes('--publish-only')) { publish(bank, map); return; }
  const keys = loadKeys();
  if (!keys.length) { console.error('No API key: set SC_AI_KEYS or create app/ai-keys.local.js'); process.exit(1); }
  const have = new Set(bank.map((t) => t.id));
  const todo = plan(+arg('--per-type', 2)).filter((s) => !have.has(s.id));
  console.log(`${bank.length} tasks stored; ${todo.length} to make`);
  let failed = 0;
  for (const s of todo) {
    const t0 = Date.now();
    try {
      const t = await AI.makeTask(s.task, s.type, s.topic, { keys, map, timeout: 180000 });
      bank.push(Object.assign({ id: s.id }, t, { source: 'bank' }));
      fs.writeFileSync(BANK, JSON.stringify(bank, null, 1) + '\n');
      console.log(`  ${s.id} (${s.topic}): ${t.words} words, ${t.model}, ${((Date.now() - t0) / 1000).toFixed(0)} s`);
    } catch (e) {
      failed++;
      console.log(`  ${s.id} FAILED: ${e.code || ''} ${e.message}`);
      if (e.code === 'quota' || e.code === 'offline' || e.code === 'nokey') break;
    }
  }
  publish(bank, map);
  if (failed) process.exitCode = 1;
}

main().catch((e) => { console.error(e); process.exit(1); });
